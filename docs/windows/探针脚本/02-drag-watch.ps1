# 探针 02：拖动图标期间，读图标的接口会不会卡住（验证清单 V03）
#
# 背景：macOS 上访达一把图标拖起来就不再回应询问，直到松手。这个脚本看 Windows 上是不是也这样，
#       以及松手后多久能读到新位置、图标的位移和鼠标的位移差多少、卡住的调用最后会不会自己返回。
#
# 做法：一个后台线程不停地读所有图标的位置，记下每次读取的发出和返回时刻；
#       主线程每隔十几毫秒看一次鼠标主键，记下按下和松开的时刻。结束后把两边的记录按时间排在一起。
#       全程只读，不移动图标。输出里没有图标的名字。
#
# 用法：
#   powershell -NoProfile -STA -ExecutionPolicy Bypass -File .\02-drag-watch.ps1
#   可以加 -Seconds N（默认 40）。
# 想提前结束：直接按 Esc；如果之前点过别处，先用 Alt+Tab 切回这个 PowerShell 窗口再按（观察期间 Ctrl+C 不起作用）。
#
# 请先在桌面上准备一个自己新建的空文件夹或文本文件（不要拿重要的东西试），并关掉"自动排列图标"。
# 脚本开始后，在 40 秒内做三件事：
#   1. 把这个图标拖到桌面的另一个空位，立刻松手；
#   2. 再拖一次，但按住至少 8 秒，中途慢慢移动，然后在空位松手；
#   3. 拖出去一小段，再拖回原来的位置松手（看"没有变化"时的表现）。

param(
    [int]$Seconds = 40
)

# 出错时只打印文件名、行号和错误说明，不打印含用户名的完整路径
trap { Write-Host ('出错（{0} 第 {1} 行）：{2}' -f [IO.Path]::GetFileName([string]$_.InvocationInfo.ScriptName), $_.InvocationInfo.ScriptLineNumber, $_.Exception.Message); exit 1 }

. "$PSScriptRoot\common.ps1"

Write-Section ('开始观察 {0} 秒：请按文件开头的说明拖动图标' -f $Seconds)
$lines = [DdmProbe.DragWatch]::Run($Seconds)
foreach ($line in $lines) { Write-Host $line }

Write-Host ''
Write-Host '怎么读这份结果（对应验证清单 V03）：'
Write-Host '  · "按住期间有一次读取被卡了 N 毫秒"且 N 接近按住的时长 → 和 macOS 一样，拖动期间不回应；'
Write-Host '    图标桥要沿用 macOS 版"访达一时没空"的处理，并且读取放在能取消调用的专用线程上（方案 §2.9）。'
Write-Host '  · 最后出现"后台线程 20 秒内没有结束" → 有一次调用一直不返回，正式实现必须能取消调用。'
Write-Host '  · "按住期间读取没有明显卡顿" → 拖动期间照常回应，那一套处理可以简化。'
Write-Host '  · "松手后 N 毫秒读到新位置" → 交互感知等结局要等的时间。'
Write-Host '  · "鼠标位移"与"图标位移"之差 → 系统是从哪一点起算拖动的，以及有没有被吸到网格上。'
